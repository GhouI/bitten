#!/bin/sh
# Redraw the progress chart when main moves, and publish it on the
# `progress` branch (which the README shows). Meant for cron on a machine
# that has a local copy of App.dmg; nothing from the image is published,
# only counts.
#
#   TARGET_APP=/path/App.app tools/progress-update.sh [--force]
#
# TARGET_APP        the extracted App.app (tools/dmgx extract App.dmg DIR)
# PROGRESS_HOME  where the clean checkout and the branch live
#                (default ~/.cache/bitten-progress)
# PROGRESS_JOBS  make -j (default 2; swiftc needs about 1.5 GB a job)
# PROGRESS_MIN_MEM_MB  skip this run if less memory is available (default 3000)
#
# Example crontab line (every 20 minutes):
#   */20 * * * * TARGET_APP=$HOME/app-dmg/x/App.app /path/to/bitten/tools/progress-update.sh >>$HOME/.cache/bitten-progress.log 2>&1
set -eu

: "${TARGET_APP:?set TARGET_APP to the extracted App.app}"
HOME_DIR=${PROGRESS_HOME:-$HOME/.cache/bitten-progress}
JOBS=${PROGRESS_JOBS:-2}
MIN_MEM=${PROGRESS_MIN_MEM_MB:-3000}
SELF_REPO=$(cd "$(dirname "$0")/.." && pwd)
REMOTE=$(git -C "$SELF_REPO" remote get-url origin)
SRC=$HOME_DIR/src        # clean checkout of main, built here
PUB=$HOME_DIR/branch     # checkout of the progress branch
FORCE=${1:-}

mkdir -p "$HOME_DIR"
exec 9>"$HOME_DIR/lock"
flock -n 9 || { echo "progress: another run is in progress"; exit 0; }
log() { echo "$(date -u '+%F %T') progress: $*"; }

if [ ! -d "$SRC/.git" ]; then
    git clone -q "$REMOTE" "$SRC"
fi
git -C "$SRC" fetch -q origin main
HEAD=$(git -C "$SRC" rev-parse origin/main)

if [ ! -d "$PUB/.git" ]; then
    if git ls-remote --exit-code "$REMOTE" refs/heads/progress >/dev/null; then
        git clone -q --branch progress --single-branch "$REMOTE" "$PUB"
    else
        git init -q -b progress "$PUB"
        git -C "$PUB" remote add origin "$REMOTE"
    fi
fi
git -C "$PUB" pull -q --ff-only origin progress 2>/dev/null || true

if [ "$FORCE" != "--force" ] && [ -f "$PUB/history.csv" ] &&
   grep -q ",$(echo "$HEAD" | cut -c1-12),measured," "$PUB/history.csv"; then
    exit 0      # this commit is already measured
fi

avail=$(awk '/MemAvailable/ {print int($2/1024)}' /proc/meminfo)
if [ "$avail" -lt "$MIN_MEM" ]; then
    log "only ${avail} MB available, trying again next run"
    exit 0
fi

log "building $HEAD"
git -C "$SRC" checkout -q --detach "$HEAD"
if ! nice -n 19 make -C "$SRC" -j"$JOBS" >"$HOME_DIR/build.log" 2>&1; then
    log "build failed at $HEAD (see $HOME_DIR/build.log)"
    exit 1
fi

if [ ! -f "$PUB/history.csv" ]; then
    python3 "$SELF_REPO/tools/progress.py" backfill --repo "$SRC" --out "$PUB"
fi
python3 "$SELF_REPO/tools/progress.py" measure --repo "$SRC" --mrun "$SRC/build/mrun" \
    --app "$TARGET_APP" --commit "$HEAD" --out "$PUB"

cat >"$PUB/README.md" <<'EOF'
# bitten progress

Generated by `tools/progress-update.sh` on main's every change; do not edit.
`progress.svg` is the chart shown in the main README, `history.csv` the
numbers behind it (imports of the Mac app window still missing, per commit).
EOF
git -C "$PUB" add progress.svg history.csv README.md
if git -C "$PUB" diff --cached --quiet; then
    exit 0
fi
git -C "$PUB" -c user.name="bitten progress" -c user.email="progress@bitten.invalid" \
    commit -q -m "progress: $(echo "$HEAD" | cut -c1-7)"
git -C "$PUB" push -q origin progress
log "published for $(echo "$HEAD" | cut -c1-7)"
