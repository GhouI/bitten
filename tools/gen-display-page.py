#!/usr/bin/env python3
"""Turn src/frameworks/display/page.html into page.h (a C string).

  tools/gen-display-page.py > src/frameworks/display/page.h"""
import os
src = os.path.join(os.path.dirname(__file__), "..", "src", "frameworks", "display", "page.html")
print("/* Generated by tools/gen-display-page.py from page.html; edit that. */")
print("static const char DISPLAY_PAGE[] =")
for line in open(src, encoding="utf-8").read().splitlines():
    esc = line.replace("\\", "\\\\").replace('"', '\\"')
    print('    "%s\\n"' % esc)
print(";")
