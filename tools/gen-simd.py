#!/usr/bin/env python3
"""Generate the standard library's SIMD types (stdlib SIMD.swift).

Apple's layouts, which compiled programs inline: SIMDn<Scalar> is @frozen
and holds Scalar.SIMDnStorage, a @frozen struct around a Builtin.Vec<n>x<T>
LLVM vector (so SIMD2<Float> is 8 bytes and travels in one xmm register,
SIMD3<Float> is a <3 x float> of 16 bytes). Element access goes through
extractelement/insertelement; arithmetic is written over the elements in
the protocol extensions.
"""

COUNTS = [2, 3, 4, 8, 16, 32, 64]
# Swift scalar, builtin element, mask scalar
SCALARS = [
    ("Float", "FPIEEE32", "Int32"),
    ("Double", "FPIEEE64", "Int64"),
    ("Int8", "Int8", "Int8"),
    ("Int16", "Int16", "Int16"),
    ("Int32", "Int32", "Int32"),
    ("Int64", "Int64", "Int64"),
    ("Int", "Int64", "Int"),
    ("UInt8", "Int8", "Int8"),
    ("UInt16", "Int16", "Int16"),
    ("UInt32", "Int32", "Int32"),
    ("UInt64", "Int64", "Int64"),
    ("UInt", "Int64", "Int"),
]

out = []
w = out.append

w("""// Generated by tools/gen-simd.py: SIMD vectors and their storage.

public protocol SIMDStorage {
  associatedtype Scalar: Codable, Hashable
  var scalarCount: Int { get }
  init()
  subscript(index: Int) -> Scalar { get set }
}

public protocol SIMDScalar {
  associatedtype SIMDMaskScalar: SIMDScalar & FixedWidthInteger & SignedInteger
  associatedtype SIMD2Storage: SIMDStorage where SIMD2Storage.Scalar == Self
  associatedtype SIMD4Storage: SIMDStorage where SIMD4Storage.Scalar == Self
  associatedtype SIMD8Storage: SIMDStorage where SIMD8Storage.Scalar == Self
  associatedtype SIMD16Storage: SIMDStorage where SIMD16Storage.Scalar == Self
  associatedtype SIMD32Storage: SIMDStorage where SIMD32Storage.Scalar == Self
  associatedtype SIMD64Storage: SIMDStorage where SIMD64Storage.Scalar == Self
}

infix operator .== : ComparisonPrecedence
infix operator .!= : ComparisonPrecedence
infix operator .< : ComparisonPrecedence
infix operator .<= : ComparisonPrecedence
infix operator .> : ComparisonPrecedence
infix operator .>= : ComparisonPrecedence

public protocol SIMD: SIMDStorage, Codable, Hashable, CustomStringConvertible, ExpressibleByArrayLiteral {
  associatedtype MaskStorage: SIMD where MaskStorage.Scalar: FixedWidthInteger & SignedInteger
}

extension SIMD {
  @_transparent public static var scalarCount: Int { return Self().scalarCount }
  @inlinable public var indices: Range<Int> { return 0..<scalarCount }

  @inlinable public init(repeating value: Scalar) {
    self.init()
    for i in indices { self[i] = value }
  }
  @inlinable public init<S: Sequence>(_ scalars: S) where S.Element == Scalar {
    self.init()
    var i = 0
    for s in scalars {
      _precondition(i < scalarCount, "Too many elements in sequence.")
      self[i] = s
      i += 1
    }
    _precondition(i == scalarCount, "Too few elements in sequence.")
  }
  @inlinable public init(arrayLiteral scalars: Scalar...) { self.init(scalars) }

  @inlinable public static func == (a: Self, b: Self) -> Bool {
    for i in a.indices where a[i] != b[i] { return false }
    return true
  }
  @inlinable public func hash(into hasher: inout Hasher) {
    for i in indices { hasher.combine(self[i]) }
  }
  public var description: String {
    var s = "\\(Self.self)("
    for i in indices { s += (i == 0 ? "" : ", ") + String(describing: self[i]) }
    return s + ")"
  }
  public func encode(to encoder: Encoder) throws {
    var c = encoder.unkeyedContainer()
    for i in indices { try c.encode(self[i]) }
  }
  public init(from decoder: Decoder) throws {
    self.init()
    var c = try decoder.unkeyedContainer()
    for i in indices { self[i] = try c.decode(Scalar.self) }
  }
}

extension SIMD where Scalar: FloatingPoint {
  @inlinable public static var zero: Self { return Self() }
  @inlinable public static func + (a: Self, b: Self) -> Self { var r = a; for i in r.indices { r[i] = a[i] + b[i] }; return r }
  @inlinable public static func - (a: Self, b: Self) -> Self { var r = a; for i in r.indices { r[i] = a[i] - b[i] }; return r }
  @inlinable public static func * (a: Self, b: Self) -> Self { var r = a; for i in r.indices { r[i] = a[i] * b[i] }; return r }
  @inlinable public static func / (a: Self, b: Self) -> Self { var r = a; for i in r.indices { r[i] = a[i] / b[i] }; return r }
  @inlinable public static func * (a: Self, b: Scalar) -> Self { var r = a; for i in r.indices { r[i] = a[i] * b }; return r }
  @inlinable public static func * (a: Scalar, b: Self) -> Self { return b * a }
  @inlinable public static func / (a: Self, b: Scalar) -> Self { var r = a; for i in r.indices { r[i] = a[i] / b }; return r }
  @inlinable public static func + (a: Self, b: Scalar) -> Self { var r = a; for i in r.indices { r[i] = a[i] + b }; return r }
  @inlinable public static func - (a: Self, b: Scalar) -> Self { var r = a; for i in r.indices { r[i] = a[i] - b }; return r }
  @inlinable public static prefix func - (a: Self) -> Self { var r = a; for i in r.indices { r[i] = -a[i] }; return r }
  @inlinable public static func += (a: inout Self, b: Self) { a = a + b }
  @inlinable public static func -= (a: inout Self, b: Self) { a = a - b }
  @inlinable public static func *= (a: inout Self, b: Self) { a = a * b }
  @inlinable public static func /= (a: inout Self, b: Self) { a = a / b }
  @inlinable public static func *= (a: inout Self, b: Scalar) { a = a * b }
  @inlinable public func sum() -> Scalar { var s: Scalar = 0; for i in indices { s += self[i] }; return s }
  @inlinable public func min() -> Scalar { var m = self[0]; for i in indices where self[i] < m { m = self[i] }; return m }
  @inlinable public func max() -> Scalar { var m = self[0]; for i in indices where self[i] > m { m = self[i] }; return m }
  @inlinable public func squareRoot() -> Self { var r = self; for i in r.indices { r[i] = self[i].squareRoot() }; return r }
  @inlinable public func rounded(_ rule: FloatingPointRoundingRule) -> Self {
    var r = self; for i in r.indices { r[i] = self[i].rounded(rule) }; return r
  }
}

extension SIMD where Scalar: FixedWidthInteger {
  @inlinable public static var zero: Self { return Self() }
  @inlinable public static func &+ (a: Self, b: Self) -> Self { var r = a; for i in r.indices { r[i] = a[i] &+ b[i] }; return r }
  @inlinable public static func &- (a: Self, b: Self) -> Self { var r = a; for i in r.indices { r[i] = a[i] &- b[i] }; return r }
  @inlinable public static func &* (a: Self, b: Self) -> Self { var r = a; for i in r.indices { r[i] = a[i] &* b[i] }; return r }
  @inlinable public static func / (a: Self, b: Self) -> Self { var r = a; for i in r.indices { r[i] = a[i] / b[i] }; return r }
  @inlinable public static func % (a: Self, b: Self) -> Self { var r = a; for i in r.indices { r[i] = a[i] % b[i] }; return r }
  @inlinable public static func & (a: Self, b: Self) -> Self { var r = a; for i in r.indices { r[i] = a[i] & b[i] }; return r }
  @inlinable public static func | (a: Self, b: Self) -> Self { var r = a; for i in r.indices { r[i] = a[i] | b[i] }; return r }
  @inlinable public static func ^ (a: Self, b: Self) -> Self { var r = a; for i in r.indices { r[i] = a[i] ^ b[i] }; return r }
  @inlinable public func wrappedSum() -> Scalar { var s: Scalar = 0; for i in indices { s = s &+ self[i] }; return s }
  @inlinable public func min() -> Scalar { var m = self[0]; for i in indices where self[i] < m { m = self[i] }; return m }
  @inlinable public func max() -> Scalar { var m = self[0]; for i in indices where self[i] > m { m = self[i] }; return m }
}

/// The result of comparing vectors: one signed lane per element, -1 true.
@frozen public struct SIMDMask<Storage: SIMD>: SIMD where Storage.Scalar: FixedWidthInteger & SignedInteger {
  public var _storage: Storage
  public typealias MaskStorage = Storage
  public typealias Scalar = Bool
  @_transparent public var scalarCount: Int { return _storage.scalarCount }
  @_transparent public init() { _storage = Storage() }
  public init(_ storage: Storage) { _storage = storage }
  public subscript(index: Int) -> Bool {
    @_transparent get { return _storage[index] < 0 }
    @_transparent set { _storage[index] = newValue ? -1 : 0 }
  }
}

extension SIMD where Scalar: Comparable {
  @inlinable public static func .== (a: Self, b: Self) -> SIMDMask<MaskStorage> {
    var m = SIMDMask<MaskStorage>(); for i in a.indices { m[i] = a[i] == b[i] }; return m
  }
  @inlinable public static func .!= (a: Self, b: Self) -> SIMDMask<MaskStorage> {
    var m = SIMDMask<MaskStorage>(); for i in a.indices { m[i] = a[i] != b[i] }; return m
  }
  @inlinable public static func .< (a: Self, b: Self) -> SIMDMask<MaskStorage> {
    var m = SIMDMask<MaskStorage>(); for i in a.indices { m[i] = a[i] < b[i] }; return m
  }
  @inlinable public static func .> (a: Self, b: Self) -> SIMDMask<MaskStorage> {
    var m = SIMDMask<MaskStorage>(); for i in a.indices { m[i] = a[i] > b[i] }; return m
  }
  @inlinable public static func .<= (a: Self, b: Self) -> SIMDMask<MaskStorage> {
    var m = SIMDMask<MaskStorage>(); for i in a.indices { m[i] = a[i] <= b[i] }; return m
  }
  @inlinable public static func .>= (a: Self, b: Self) -> SIMDMask<MaskStorage> {
    var m = SIMDMask<MaskStorage>(); for i in a.indices { m[i] = a[i] >= b[i] }; return m
  }
}

@inlinable public func any<Storage>(_ mask: SIMDMask<Storage>) -> Bool {
  for i in mask.indices where mask[i] { return true }
  return false
}
@inlinable public func all<Storage>(_ mask: SIMDMask<Storage>) -> Bool {
  for i in mask.indices where !mask[i] { return false }
  return true
}
""")

# The Bool storages: a mask lane per element, over an integer vector.
for n in COUNTS:
    if n == 3:
        continue

# Vector types.
lanes = {2: "x y", 3: "x y z", 4: "x y z w"}
for n in COUNTS:
    store = "SIMD4Storage" if n == 3 else f"SIMD{n}Storage"
    w(f"""
@frozen public struct SIMD{n}<Scalar: SIMDScalar>: SIMD {{
  public var _storage: Scalar.{store}
  public typealias MaskStorage = SIMD{n}<Scalar.SIMDMaskScalar>
  @_transparent public var scalarCount: Int {{ return {n} }}
  @_transparent public init() {{ _storage = Scalar.{store}() }}
  public subscript(index: Int) -> Scalar {{
    @_transparent get {{
      _precondition(index >= 0 && index < {n}, "Index out of bounds")
      return _storage[index]
    }}
    @_transparent set {{
      _precondition(index >= 0 && index < {n}, "Index out of bounds")
      _storage[index] = newValue
    }}
  }}""")
    if n <= 4:
        names = lanes[n].split()
        params = ", ".join(f"_ v{i}: Scalar" for i in range(n))
        body = "; ".join(f"self[{i}] = v{i}" for i in range(n))
        w(f"  @_transparent public init({params}) {{ self.init(); {body} }}")
        labelled = ", ".join(f"{nm}: Scalar" for nm in names)
        lbody = "; ".join(f"self[{i}] = {nm}" for i, nm in enumerate(names))
        w(f"  @_transparent public init({labelled}) {{ self.init(); {lbody} }}")
        for i, nm in enumerate(names):
            w(f"  public var {nm}: Scalar {{ @_transparent get {{ return self[{i}] }} @_transparent set {{ self[{i}] = newValue }} }}")
    if n in (8, 16):
        params = ", ".join(f"_ v{i}: Scalar" for i in range(n))
        body = "; ".join(f"self[{i}] = v{i}" for i in range(n))
        w(f"  @_transparent public init({params}) {{ self.init(); {body} }}")
    if n >= 8:
        h = n // 2
        w(f"  @inlinable public init(lowHalf: SIMD{h}<Scalar>, highHalf: SIMD{h}<Scalar>) {{ self.init(); for i in 0..<{h} {{ self[i] = lowHalf[i]; self[{h} + i] = highHalf[i] }} }}")
        w(f"  @inlinable public var lowHalf: SIMD{h}<Scalar> {{ var r = SIMD{h}<Scalar>(); for i in 0..<{h} {{ r[i] = self[i] }}; return r }}")
        w(f"  @inlinable public var highHalf: SIMD{h}<Scalar> {{ var r = SIMD{h}<Scalar>(); for i in 0..<{h} {{ r[i] = self[{h} + i] }}; return r }}")
    if n == 3:
        w("  @_transparent public init(_ xy: SIMD2<Scalar>, _ z: Scalar) { self.init(xy[0], xy[1], z) }")
    if n == 4:
        w("  @_transparent public init(_ xyz: SIMD3<Scalar>, _ w: Scalar) { self.init(xyz[0], xyz[1], xyz[2], w) }")
        w("  @_transparent public init(lowHalf: SIMD2<Scalar>, highHalf: SIMD2<Scalar>) { self.init(lowHalf[0], lowHalf[1], highHalf[0], highHalf[1]) }")
    w("}")
    w(f"extension SIMD{n}: Sendable where Scalar: Sendable {{}}")

# Scalar conformances and their storage.
for swift, el, mask in SCALARS:
    w(f"\nextension {swift}: SIMDScalar {{")
    w(f"  public typealias SIMDMaskScalar = {mask}")
    for n in COUNTS:
        if n == 3:
            continue
        vec = f"Builtin.Vec{n}x{el}"
        bits = {"FPIEEE32": 32, "FPIEEE64": 64, "Int8": 8, "Int16": 16, "Int32": 32, "Int64": 64}[el]
        align = min(n * bits // 8, 16)
        w(f"""  @frozen @_alignment({align}) public struct SIMD{n}Storage: SIMDStorage, Sendable {{
    public var _value: {vec}
    @_transparent public var scalarCount: Int {{ return {n} }}
    @_transparent public init() {{ _value = Builtin.zeroInitializer() }}
    @_transparent public init(_ _builtin: {vec}) {{ _value = _builtin }}
    public subscript(index: Int) -> {swift} {{
      @_transparent get {{
        return {swift}(Builtin.extractelement_Vec{n}x{el}_Int32(_value, Int32(truncatingIfNeeded: index)._value))
      }}
      @_transparent set {{
        _value = Builtin.insertelement_Vec{n}x{el}_{el}_Int32(_value, newValue._value, Int32(truncatingIfNeeded: index)._value)
      }}
    }}
  }}""")
    w("}")

# SIMD3 stores in a 3-wide vector of its own (Apple's <3 x T>, 16 bytes for
# 32-bit scalars), reached through SIMD4Storage's slot: give each scalar a
# SIMD3Storage and make SIMD3 use it.
src = "\n".join(out)
# Replace SIMD3's use of SIMD4Storage with SIMD3Storage.
src = src.replace("public var _storage: Scalar.SIMD3Storage", "public var _storage: Scalar.SIMD3Storage")
print(src)
