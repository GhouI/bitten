static uint32_t fnv(const uint8_t *p, size_t n) {
    uint32_t h = 2166136261u;
    for (size_t i = 0; i < n; i++) { h ^= p[i]; h *= 16777619u; }
    return h;
}

static void lzfse_tests(void) {
    enum { LZFSE = 0x801, LZVN = 0x900 };
    static uint8_t out[8192], packed[8300];
    CHECK(compression_decode_buffer(out, sizeof out, lzfse_svg, sizeof lzfse_svg, NULL, LZFSE) == 7208);
    CHECK(memcmp(out, "<?xml version=\"1.0\"", 19) == 0 && memcmp(out + 7208 - 7, "</svg>", 6) == 0);
    CHECK(fnv(out, 7208) == 0xeb0c0f8c);
    /* too small a buffer: the beginning */
    CHECK(compression_decode_buffer(out, 100, lzfse_svg, sizeof lzfse_svg, NULL, LZFSE) == 100);
    CHECK(memcmp(out, "<?xml version=\"1.0\"", 19) == 0);
    /* damaged: nothing */
    uint8_t bad[sizeof lzfse_svg];
    memcpy(bad, lzfse_svg, sizeof bad);
    bad[sizeof bad / 2] ^= 0x5a;
    size_t got = compression_decode_buffer(out, sizeof out, bad, sizeof bad, NULL, LZFSE);
    CHECK(got == 0 || fnv(out, got) != 0xeb0c0f8c);
    CHECK(compression_decode_buffer(out, sizeof out, lzvn_block, sizeof lzvn_block, NULL, LZVN) == 1024);
    CHECK(fnv(out, 1024) == 0x1f116dc5);
    /* encoding (stored blocks) round-trips */
    for (int alg = LZFSE; alg <= LZVN; alg += LZVN - LZFSE) {
        size_t n = compression_encode_buffer(packed, sizeof packed, (const uint8_t *)short_text, sizeof short_text - 1, NULL, alg);
        CHECK(n > 0);
        CHECK(compression_decode_buffer(out, sizeof out, packed, n, NULL, alg) == sizeof short_text - 1);
        CHECK(memcmp(out, short_text, sizeof short_text - 1) == 0);
    }
}

