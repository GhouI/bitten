// Icon files (.icns): NSImage loads their PNG entries as representations.
#import <AppKit/AppKit.h>
#include <stdio.h>
#include <stdlib.h>

#define CHECK(c) do { if (!(c)) { printf("FAIL %s:%d: %s\n", __FILE__, __LINE__, #c); exit(1); } } while (0)

/* ic11: a 2x2 red PNG (16 points @2x); a raw ARGB entry (skipped); ic07: a
 * 4x4 blue PNG (128 points). */
static const unsigned char icns[] = {
    0x69, 0x63, 0x6e, 0x73, 0x00, 0x00, 0x00, 0xbc, 0x69, 0x63, 0x31, 0x31, 0x00, 0x00, 0x00, 0x52, 0x89,
    0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00,
    0x00, 0x02, 0x00, 0x00, 0x00, 0x02, 0x08, 0x06, 0x00, 0x00, 0x00, 0x72, 0xb6, 0x0d, 0x24, 0x00, 0x00,
    0x00, 0x11, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0xf8, 0xcf, 0xc0, 0xf0, 0x1f, 0x84, 0x19, 0x60,
    0x0c, 0x00, 0x47, 0xca, 0x07, 0xf9, 0x67, 0x59, 0x6e, 0xb7, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e,
    0x44, 0xae, 0x42, 0x60, 0x82, 0x41, 0x52, 0x47, 0x42, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x69, 0x63, 0x30, 0x37, 0x00, 0x00, 0x00, 0x52, 0x89, 0x50, 0x4e, 0x47, 0x0d,
    0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00,
    0x00, 0x04, 0x08, 0x06, 0x00, 0x00, 0x00, 0xa9, 0xf1, 0x9e, 0x7e, 0x00, 0x00, 0x00, 0x11, 0x49, 0x44,
    0x41, 0x54, 0x78, 0x9c, 0x63, 0x60, 0x60, 0xf8, 0xff, 0x1f, 0x15, 0x93, 0x2c, 0x00, 0x00, 0x1c, 0x60,
    0x1f, 0xe1, 0xb6, 0x90, 0xec, 0xe7, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60,
    0x82,
};

int main(void) {
    @autoreleasepool {
        [NSApplication sharedApplication];
        NSImage *img = [[NSImage alloc] initWithData:[NSData dataWithBytes:icns length:sizeof icns]];
        CHECK(img != nil);
        CHECK(NSEqualSizes(img.size, NSMakeSize(128, 128)));
        CHECK(img.representations.count == 2);
        NSBitmapImageRep *first = (NSBitmapImageRep *)img.representations[0];
        NSBitmapImageRep *second = (NSBitmapImageRep *)img.representations[1];
        CHECK(first.pixelsWide == 4 && NSEqualSizes(first.size, NSMakeSize(128, 128)));
        CHECK(second.pixelsWide == 2 && NSEqualSizes(second.size, NSMakeSize(16, 16)));
        // Not an icon file, not an image: nil.
        CHECK([[NSImage alloc] initWithData:[NSData dataWithBytes:"icns\0\0\0\x08" length:8]] == nil);
        puts("appkit icns ok");
    }
    return 0;
}
